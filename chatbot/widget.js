/* A1 phone assistant: a chat bubble for any web page.
 *
 *   <script src="https://YOUR-CHAT-SERVER/widget.js" defer></script>
 *
 * Optional attributes on the script tag:
 *   data-api="https://chat.example.mk"  chat server (default: where widget.js came from)
 *   data-lang="mk" | "en"               interface language (default: the page's <html lang>)
 */
(function () {
  "use strict";
  var script = document.currentScript;
  var api = (script && script.getAttribute("data-api")) ||
            (script && script.src ? new URL(script.src).origin : location.origin);
  var lang = ((script && script.getAttribute("data-lang")) ||
              document.documentElement.lang || navigator.language || "mk").slice(0, 2);
  lang = lang === "en" ? "en" : "mk";

  var T = {
    mk: { title: "A1 Асистент за телефони", open: "Отвори разговор", close: "Затвори",
          placeholder: "Прашајте за телефон, цена, боја…", send: "Испрати",
          hello: "Здраво! 👋 Можам да ви помогнам да изберете телефон од A1. Прашајте ме за цени, рати, бои или споредба.",
          error: "Асистентот моментално не е достапен. Обидете се повторно подоцна.",
          busy: "Има многу прашања во моментов. Обидете се повторно за една минута.",
          note: "Одговорите ги дава вештачка интелигенција и може да содржат грешки. Проверете ја цената на a1.mk. Прашањата се зачувуваат анонимно за подобрување на услугата.",
          reset: "Нов разговор" },
    en: { title: "A1 Phone Assistant", open: "Open chat", close: "Close",
          placeholder: "Ask about a phone, price, colour…", send: "Send",
          hello: "Hi! 👋 I can help you choose a phone from A1. Ask me about prices, installments, colours or comparisons.",
          error: "The assistant is not available right now. Please try again later.",
          busy: "Lots of questions right now. Please try again in a minute.",
          note: "Answers are generated by AI and may contain mistakes. Check the price on a1.mk. Questions are saved anonymously to improve the service.",
          reset: "New chat" }
  }[lang];

  var KEY = "a1chat.messages";
  // A random id for this chat, so saved questions can be grouped per conversation.
  var session = "";
  try { session = sessionStorage.getItem("a1chat.session") || ""; } catch (e) {}
  if (!session) {
    session = Date.now().toString(36) + "-" + Math.random().toString(36).slice(2, 10);
    try { sessionStorage.setItem("a1chat.session", session); } catch (e) {}
  }
  var messages = [];
  try { messages = JSON.parse(sessionStorage.getItem(KEY) || "[]"); } catch (e) { messages = []; }
  function save() { try { sessionStorage.setItem(KEY, JSON.stringify(messages.slice(-20))); } catch (e) {} }

  var css = [
    ".a1c-btn{position:fixed;right:20px;bottom:20px;width:60px;height:60px;border-radius:50%;border:0;",
    "background:#da291c;color:#fff;cursor:pointer;box-shadow:0 4px 14px rgba(0,0,0,.25);z-index:2147483000;",
    "display:flex;align-items:center;justify-content:center}",
    ".a1c-btn svg{width:28px;height:28px}",
    ".a1c-panel{position:fixed;right:20px;bottom:92px;width:370px;max-width:calc(100vw - 32px);height:560px;",
    "max-height:calc(100vh - 120px);background:#fff;color:#1a1a1a;border-radius:14px;overflow:hidden;",
    "box-shadow:0 10px 40px rgba(0,0,0,.25);display:none;flex-direction:column;z-index:2147483000;",
    "font:15px/1.45 system-ui,-apple-system,'Segoe UI',Roboto,sans-serif}",
    ".a1c-panel.open{display:flex}",
    ".a1c-head{background:#da291c;color:#fff;padding:12px 14px;display:flex;align-items:center;gap:8px}",
    ".a1c-head b{flex:1;font-size:16px}",
    ".a1c-head button{background:none;border:0;color:#fff;cursor:pointer;font-size:13px;opacity:.9;padding:4px}",
    ".a1c-log{flex:1;overflow-y:auto;padding:14px;display:flex;flex-direction:column;gap:10px;background:#f6f6f7}",
    ".a1c-msg{max-width:85%;padding:9px 12px;border-radius:12px;white-space:normal;word-wrap:break-word}",
    ".a1c-msg p{margin:0 0 6px}.a1c-msg p:last-child{margin:0}.a1c-msg ul{margin:4px 0;padding-left:18px}",
    ".a1c-msg a{color:#da291c}",
    ".a1c-user{align-self:flex-end;background:#da291c;color:#fff;border-bottom-right-radius:4px}",
    ".a1c-user a{color:#fff}",
    ".a1c-bot{align-self:flex-start;background:#fff;border:1px solid #e3e3e6;border-bottom-left-radius:4px}",
    ".a1c-err{border-color:#f0b4ae;background:#fff4f3}",
    ".a1c-dots span{display:inline-block;width:6px;height:6px;margin:0 2px;border-radius:50%;background:#999;",
    "animation:a1c-b 1s infinite}.a1c-dots span:nth-child(2){animation-delay:.15s}.a1c-dots span:nth-child(3){animation-delay:.3s}",
    "@keyframes a1c-b{0%,80%,100%{opacity:.3}40%{opacity:1}}",
    ".a1c-form{display:flex;gap:8px;padding:10px;border-top:1px solid #e3e3e6;background:#fff}",
    ".a1c-form textarea{flex:1;resize:none;border:1px solid #cfcfd4;border-radius:10px;padding:8px 10px;",
    "font:inherit;height:40px;max-height:100px;color:inherit;background:#fff}",
    ".a1c-form button{border:0;border-radius:10px;background:#da291c;color:#fff;padding:0 14px;cursor:pointer;font:inherit}",
    ".a1c-form button:disabled{opacity:.5;cursor:default}",
    ".a1c-note{font-size:11px;color:#777;padding:0 12px 8px;background:#fff}",
    "@media (max-width:480px){.a1c-panel{right:8px;left:8px;bottom:84px;width:auto;height:calc(100vh - 100px)}}"
  ].join("");

  var style = document.createElement("style");
  style.textContent = css;
  document.head.appendChild(style);

  var chatIcon = '<svg viewBox="0 0 24 24" fill="currentColor" aria-hidden="true"><path d="M4 4h16a2 2 0 0 1 2 2v10a2 2 0 0 1-2 2H8l-4 4V6a2 2 0 0 1 2-2z"/></svg>';
  var closeIcon = '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5" aria-hidden="true"><path d="M6 6l12 12M18 6L6 18"/></svg>';

  var btn = document.createElement("button");
  btn.className = "a1c-btn";
  btn.setAttribute("aria-label", T.open);
  btn.innerHTML = chatIcon;

  var panel = document.createElement("div");
  panel.className = "a1c-panel";
  panel.setAttribute("role", "dialog");
  panel.setAttribute("aria-label", T.title);
  panel.innerHTML =
    '<div class="a1c-head"><b></b><button type="button" class="a1c-reset"></button></div>' +
    '<div class="a1c-log" aria-live="polite"></div>' +
    '<form class="a1c-form"><textarea rows="1"></textarea><button type="submit"></button></form>' +
    '<div class="a1c-note"></div>';
  panel.querySelector("b").textContent = T.title;
  panel.querySelector(".a1c-reset").textContent = T.reset;
  panel.querySelector("textarea").placeholder = T.placeholder;
  panel.querySelector("textarea").setAttribute("aria-label", T.placeholder);
  panel.querySelector(".a1c-form button").textContent = T.send;
  panel.querySelector(".a1c-note").textContent = T.note;
  document.body.appendChild(panel);
  document.body.appendChild(btn);

  var log = panel.querySelector(".a1c-log");
  var form = panel.querySelector("form");
  var input = panel.querySelector("textarea");
  var sendBtn = panel.querySelector(".a1c-form button");
  var busy = false;

  function esc(s) {
    return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
  }

  // Just enough Markdown for the model's answers: paragraphs, "- " lists,
  // **bold**, [text](url) and bare links. Everything is escaped first.
  function render(text) {
    var html = [], list = false;
    esc(text).split("\n").forEach(function (line) {
      line = line
        .replace(/\*\*(.+?)\*\*/g, "<b>$1</b>")
        .replace(/\[([^\]]+)\]\((https?:\/\/[^\s)]+)\)/g, '<a href="$2" target="_blank" rel="noopener">$1</a>')
        .replace(/(^|[\s(])(https?:\/\/[^\s<)]+[^\s<).,])/g, '$1<a href="$2" target="_blank" rel="noopener">$2</a>');
      var item = /^\s*(?:[-*•]|\d+[.)])\s+(.*)/.exec(line);
      if (item) {
        if (!list) { html.push("<ul>"); list = true; }
        html.push("<li>" + item[1] + "</li>");
        return;
      }
      if (list) { html.push("</ul>"); list = false; }
      line = line.replace(/^#+\s*/, "");
      if (line.trim()) html.push("<p>" + line + "</p>");
    });
    if (list) html.push("</ul>");
    return html.join("");
  }

  function bubble(role, text, extra) {
    var div = document.createElement("div");
    div.className = "a1c-msg " + (role === "user" ? "a1c-user" : "a1c-bot") + (extra ? " " + extra : "");
    div.innerHTML = render(text);
    log.appendChild(div);
    log.scrollTop = log.scrollHeight;
    return div;
  }

  function showAll() {
    log.innerHTML = "";
    bubble("assistant", T.hello);
    messages.forEach(function (m) { bubble(m.role, m.content); });
  }

  function setOpen(open) {
    panel.classList.toggle("open", open);
    btn.innerHTML = open ? closeIcon : chatIcon;
    btn.setAttribute("aria-label", open ? T.close : T.open);
    if (open) { input.focus(); log.scrollTop = log.scrollHeight; }
  }

  btn.addEventListener("click", function () { setOpen(!panel.classList.contains("open")); });
  panel.querySelector(".a1c-reset").addEventListener("click", function () {
    if (busy) return;
    messages = []; save(); showAll(); input.focus();
    session = Date.now().toString(36) + "-" + Math.random().toString(36).slice(2, 10);
    try { sessionStorage.setItem("a1chat.session", session); } catch (e) {}
  });
  input.addEventListener("keydown", function (e) {
    if (e.key === "Enter" && !e.shiftKey) { e.preventDefault(); form.requestSubmit ? form.requestSubmit() : send(); }
  });
  form.addEventListener("submit", function (e) { e.preventDefault(); send(); });

  function send() {
    var text = input.value.trim();
    if (!text || busy) return;
    busy = true; sendBtn.disabled = true;
    input.value = "";
    messages.push({ role: "user", content: text });
    save();
    bubble("user", text);
    var out = bubble("assistant", "");
    out.innerHTML = '<span class="a1c-dots"><span></span><span></span><span></span></span>';
    var answer = "";

    fetch(api + "/api/chat", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ messages: messages.slice(-12), session: session })
    }).then(function (res) {
      if (!res.ok || !res.body) throw new Error(res.status === 503 ? "busy" : "http " + res.status);
      var reader = res.body.getReader();
      var dec = new TextDecoder();
      function pump() {
        return reader.read().then(function (r) {
          if (r.done) return;
          answer += dec.decode(r.value, { stream: true });
          out.innerHTML = render(answer);
          log.scrollTop = log.scrollHeight;
          return pump();
        });
      }
      return pump();
    }).then(function () {
      if (!answer.trim()) throw new Error("empty");
      messages.push({ role: "assistant", content: answer.trim() });
      save();
    }).catch(function (err) {
      if (answer.trim()) {  // cut off midway: keep what arrived
        messages.push({ role: "assistant", content: answer.trim() });
        save();
        return;
      }
      messages.pop();  // let the user ask again
      save();
      out.className += " a1c-err";
      out.innerHTML = render(err && err.message === "busy" ? T.busy : T.error);
    }).then(function () {
      busy = false; sendBtn.disabled = false; input.focus();
    });
  }

  showAll();
})();
